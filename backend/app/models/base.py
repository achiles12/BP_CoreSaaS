"""Declarative bases for the two schema tracks (design B02 §3.1–3.3).

Two separate MetaData objects so each Alembic track (public / tenant) and the
drift test only ever see their own tables.

- PublicBase: tables in the shared `public` schema, declared with an EXPLICIT
  schema="public" so cross-schema foreign keys from tenant tables render as
  `public.users` and are never affected by tenant schema translation.
- TenantBase: tables declared with the placeholder schema "tenant". A session
  maps it to the real schema with schema_translate_map={"tenant": "tenant_<slug>"}
  (core.tenancy.tenant_session). The placeholder never exists in Postgres.
"""

import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.db import NAMING_CONVENTION

PUBLIC_SCHEMA = "public"
TENANT_SCHEMA_PLACEHOLDER = "tenant"


class PublicBase(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION, schema=PUBLIC_SCHEMA)


class TenantBase(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION, schema=TENANT_SCHEMA_PLACEHOLDER)


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUID primary key generated by Postgres (gen_random_uuid, core in PG13+)."""
    return mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )


def created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


def updated_at() -> Mapped[datetime]:
    # onupdate keeps it current for ORM updates; raw SQL updates must set it.
    return mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now()
    )
